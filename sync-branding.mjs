import { readFileSync, writeFileSync } from "node:fs";
const root = new URL("./", import.meta.url);
const source = readFileSync(new URL("packages/constants/src/branding.ts", root), "utf8");
const match = source.match(/export const BRAND_NAME = ("(?:[^"\\]|\\.)*");/);
if (!match) throw new Error("BRAND_NAME must be a double-quoted string literal");
const name = JSON.parse(match[1]);
for (const file of [
  "apps/web/manifest.json",
  "apps/web/public/manifest.json",
  "apps/web/public/site.webmanifest.json",
  "apps/admin/public/site.webmanifest.json",
  "apps/space/public/site.webmanifest.json",
]) {
  const url = new URL(file, root);
  const manifest = JSON.parse(readFileSync(url, "utf8"));
  const admin = file.includes("/admin/");
  manifest.name = `${name}研发管理平台${admin ? " - 管理后台" : ""}`;
  manifest.short_name = `${name}${admin ? "后台" : ""}`;
  manifest.description = `${name}${file.includes("/space/") ? "研发管理平台的公开项目视图" : `研发协作平台${admin ? "管理后台" : ""}`}`;
  writeFileSync(url, JSON.stringify(manifest, null, 2) + "\n");
}
writeFileSync(
  new URL("apps/api/plane/utils/branding.py", root),
  `# Generated by sync-branding.mjs; edit packages/constants/src/branding.ts.\nBRAND_NAME = ${JSON.stringify(name)}\n`
);
console.log(`Branding synchronized: ${name}`);
